#!/usr/bin/env bash
# ===========================================================================
# 终端输出公共库
# ===========================================================================
# 为什么要有这个文件：
#   最早 menu.sh / deploy.sh / configure.sh 各自抄了一份 ok/warn/err/step。
#   看起来「反正内容一样，多抄一份也没事」，实际上是个定时炸弹 ——
#   哪天只改了其中一份，同样的提示在不同入口下就会长得不一样，
#   而且这种 bug 完全不报错，只有肉眼对比才看得出。
#
#   所以统一收进这里，所有脚本都 `source` 它。
#
# 用法（在被引用的脚本顶部）：
#   . "$(dirname "$0")/lib-ui.sh"
#
# ⚠️ 这个文件**只定义函数和颜色**，不做任何事、不产生任何输出。
#    这样无论谁在什么时机 source 它，都不会有副作用。
# ===========================================================================

# ---------------------------------------------------------------------------
# 颜色
# ---------------------------------------------------------------------------
# 只有在「真的连着终端」时才上色。
# 如果输出被重定向到文件、或被管道接走（比如自动化测试），
# 就全部置空 —— 否则文件里会塞满 \033[32m 这种乱码。
if [ -t 1 ]; then
  BOLD="\033[1m"
  DIM="\033[2m"
  GREEN="\033[32m"
  YELLOW="\033[33m"
  RED="\033[31m"
  CYAN="\033[36m"
  BLUE="\033[34m"
  RESET="\033[0m"
else
  BOLD=""; DIM=""; GREEN=""; YELLOW=""; RED=""; CYAN=""; BLUE=""; RESET=""
fi

# ---------------------------------------------------------------------------
# 输出函数
# ---------------------------------------------------------------------------
# 统一格式：[成功] / [注意] / [失败] / [信息]，后面跟一句人话。
# 全部中文，且每条都有明确含义 —— 不打哑谜、不丢英文。
ok()   { printf "${GREEN}[成功]${RESET} %s\n" "$1"; }
warn() { printf "${YELLOW}[注意]${RESET} %s\n" "$1"; }
err()  { printf "${RED}[失败]${RESET} %s\n" "$1"; }
info() { printf "${CYAN}[信息]${RESET} %s\n" "$1"; }

# 小节标题
step() { printf "\n${BOLD}${CYAN}== %s ==${RESET}\n" "$1"; }

# 一条分隔线
hr()   { printf "${DIM}%s${RESET}\n" "------------------------------------------------------------"; }

# ---------------------------------------------------------------------------
# 交互
# ---------------------------------------------------------------------------
# ⚠️ read 一定要带 `|| true`：
#    管道输入结束时 read 会返回非 0，而脚本开头是 `set -u`（甚至 set -e），
#    不兜住就会「莫名其妙地整个脚本中止」。这个坑踩过一次。
pause() {
  printf "\n${DIM}按回车继续...${RESET}"
  read -r _ || true
}

# 是/否确认，默认「是」（直接回车 = 是）
#
# ⚠️ 只用于**无害**的确认（例如「现在开始安装吗？」）。
#    破坏性操作（覆盖配置、删除东西）请改用 confirm_danger。
confirm() {
  local prompt="$1" answer=""
  printf "%s (Y/n) " "$prompt"
  read -r answer || true
  case "$answer" in
    [Nn]*) return 1 ;;
    *)     return 0 ;;
  esac
}

# 是/否确认，默认「否」（直接回车 = 否）
#
# 🔴 为什么必须有这个函数（踩过的坑）：
#    configure.sh 里有一句 `confirm "确实要用新填的清单覆盖现有配置吗？"` ——
#    用的是默认「是」的版本。用户敲了半天配置，最后一步习惯性连按回车，
#    结果**直接就把原有配置覆盖了**，且没有任何挽回余地。
#    破坏性操作的默认值必须是「否」：想执行得明确敲 y。
#    这样「手滑回车」只会安全地取消，而不是把东西弄坏。
confirm_danger() {
  local prompt="$1" answer=""
  printf "%s (y/N) " "$prompt"
  read -r answer || true
  case "$answer" in
    [Yy]*) return 0 ;;
    *)     return 1 ;;
  esac
}
